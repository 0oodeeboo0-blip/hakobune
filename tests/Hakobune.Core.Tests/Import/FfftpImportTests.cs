    [Theory]
    [InlineData(DefaultMasterPassword, null, "hakobune-pass")]
    [InlineData(DefaultMasterPassword, "", "hakobune-pass")]
    [InlineData(CustomMasterPassword, "hakobune-master", "hakobune-pass")]
    [InlineData("0C000102030405060708090a0b0c0d0e0f:00d9a80780b7cadc4e1b394b14766850c97f96fc3dbf8d509bcacf8599a32fc5", null, "箱舟-pass")]
    [InlineData("0C000102030405060708090a0b0c0d0e0f:e6050f81bc639a145ded8645110385d7a41b7fa0b54e4f1707febed744aa0609", null, "")]
    [InlineData("0BLBX@dCN@^BdFJAZFaCAV@hDD@XC", null, "hakobune-pass")]
    [InlineData("0AHFRLmJU^MiHjZNiKAZLdK@GRLmLkVN", null, "hakobune-pass")]
    [InlineData("HFRLmJU^MiHjZNiKAZLdK@GRLmLkVN", null, "hakobune-pass")]
    public void Saved_passwords_are_decoded(string stored, string? master, string expected) =>
        Assert.Equal(expected, FfftpPasswords.Decode(stored, master));

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("0C00:zz")]
    [InlineData("0D0001")]
    public void Unknown_or_broken_passwords_give_nothing(string? stored) => Assert.Null(FfftpPasswords.Decode(stored, null));

    [Fact]
    public void A_wrong_master_password_does_not_give_the_password()
    {
        Assert.NotEqual("hakobune-pass", FfftpPasswords.Decode(CustomMasterPassword, null));
        Assert.NotEqual("hakobune-pass", FfftpPasswords.Decode(CustomMasterPassword, "wrong"));
    }

    [Fact]
    public void The_master_password_is_checked_against_the_saved_hash()
    {
        var settings = new FfftpSettings();
        settings.Set("FFFTP", "CredentialSalt", 0x12345678);
        settings.Set("FFFTP", "CredentialCheck", DefaultMasterCheck);

        Assert.True(FfftpPasswords.CheckMasterPassword(settings, null));
        Assert.True(FfftpPasswords.CheckMasterPassword(settings, "DefaultPassword"));
        Assert.False(FfftpPasswords.CheckMasterPassword(settings, "hakobune-master"));
        // 確かめる値が無ければ、どれでも通す
        Assert.True(FfftpPasswords.CheckMasterPassword(new FfftpSettings(), "anything"));
    }

    [Fact]
    public void Hosts_groups_and_common_settings_are_read_from_ffftp_ini()
    {
        var list = FfftpHosts.Read(FfftpSettings.Load(Encoding.ASCII.GetBytes(Ini)));

        Assert.False(list.IsEncrypted);
        Assert.False(list.NeedsMasterPassword);
        Assert.Equal(new[] { "ショップ（本番）", "test", "ブログ", "old" }, list.Hosts.Select(host => host.Name).ToArray());

        var shop = list.Hosts[0];
        Assert.Equal(new[] { "仕事" }, shop.Groups.ToArray());
        Assert.Equal("ftp.example.com", shop.Host);
        Assert.Equal(21, shop.Port);
        Assert.Equal("web", shop.UserName);
        Assert.Equal("hakobune-pass", FfftpPasswords.Decode(shop.StoredPassword, null));
        Assert.Equal(@"C:\Users\箱舟\shop", shop.LocalDirectory);
        Assert.Equal("/var/www/html", shop.RemoteDirectory);
        Assert.False(shop.Passive); // 共通の設定（DefaultHost）から
        Assert.False(shop.AllowPlain);
        Assert.True(shop.AllowExplicitTls);
        Assert.False(shop.AllowImplicitTls);
        Assert.Equal(0, shop.FileNameKanji);
        Assert.Equal(4, shop.MaxConnections);

        var test = list.Hosts[1];
        Assert.Equal(new[] { "仕事", "案件A" }, test.Groups.ToArray());
        Assert.Equal(2121, test.Port);
        Assert.True(test.Passive);
        Assert.True(test.AllowPlain && test.AllowExplicitTls && test.AllowImplicitTls);
        Assert.Equal(-1, test.FileNameKanji);
        Assert.Null(test.MaxConnections);

        var blog = list.Hosts[2];
        Assert.Empty(blog.Groups);
        Assert.True(blog.Anonymous);
        Assert.Equal("", blog.UserName);
        Assert.Null(blog.StoredPassword);

        Assert.Equal("hakobune-pass", FfftpPasswords.Decode(list.Hosts[3].StoredPassword, null));
    }

    [Fact]
    public void A_settings_file_saved_with_regedit_is_read_too()
    {
        const string reg = """
            Windows Registry Editor Version 5.00

            [HKEY_CURRENT_USER\Software\sota\FFFTP]
            "Version"=dword:00001644
            "CredentialSalt"=dword:12345678
            "CredentialCheck"="H@BLG@NIHOJOGFIOMBMKA@EMKHEGKOH@IGNNFDOM"

            [HKEY_CURRENT_USER\Software\sota\FFFTP\Options]
            "SetNum"=dword:00000001

            [HKEY_CURRENT_USER\Software\sota\FFFTP\Options\Host0]
            "Set"=dword:00000000
            "HostName"="ショップ \"本番\""
            "HostAdrs"="ftp.example.com"
            "Password"="0C000102030405060708090a0b0c0d0e0f:57002f455d023266a80c3b506acdbbb3cea1e601639be0638d4d44f20372f5c3"
            "LocalDir"="C:\\Users\\箱舟"
            "Port"=dword:00000015
            "Sort"=hex:ff,ff,ff,ff
            "Bmarks"=hex(7):48,00,20,00,2f,00,77,00,77,00,77,00,00,00,\
              00,00

            """;
        var bytes = Encoding.Unicode.GetPreamble().Concat(Encoding.Unicode.GetBytes(reg.Replace("\n", "\r\n", StringComparison.Ordinal))).ToArray();

        var list = FfftpHosts.Read(FfftpSettings.Load(bytes));

        // マスターパスワードを決めてある（確かめる値が DefaultPassword と合わない）
        Assert.True(list.NeedsMasterPassword);
        var host = Assert.Single(list.Hosts);
        Assert.Equal("ショップ \"本番\"", host.Name);
        Assert.Equal(@"C:\Users\箱舟", host.LocalDirectory);
        Assert.Equal(21, host.Port);
        Assert.Equal("hakobune-pass", FfftpPasswords.Decode(host.StoredPassword, "hakobune-master"));
    }

    [Fact]
    public void Old_ini_files_in_shift_jis_are_read()
    {
        var ini = "[FFFTP]\r\nVersion=1960\r\n[FFFTP\\Options]\r\nSetNum=1\r\n[FFFTP\\Options\\Host0]\r\nHostName=\\83V\\83\\87\\83b\\83v\r\nHostAdrs=ftp.example.com\r\n";

        var host = Assert.Single(FfftpHosts.Read(FfftpSettings.Load(Encoding.ASCII.GetBytes(ini))).Hosts);

        Assert.Equal("ショップ", host.Name);
    }

    [Fact]
    public void Settings_encrypted_as_a_whole_are_not_read()
    {
        var settings = new FfftpSettings();
        settings.Set("FFFTP", "EncryptAll", 1);
        settings.Set(@"FFFTP\EncryptedOptions\Host0", "HostAdrs", new byte[] { 1, 2, 3 });

        var list = FfftpHosts.Read(settings);

        Assert.True(list.IsEncrypted);
        Assert.Empty(list.Hosts);
    }
}
