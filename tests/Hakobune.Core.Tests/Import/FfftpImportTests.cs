using System.Text;
using Hakobune.Core.Import;

namespace Hakobune.Core.Tests.Import;

/// <summary>FFFTP の設定（ffftp.ini・.reg）から接続先とパスワードを読む。値は FFFTP 5.8 のコードどおりに作ったもの。</summary>
public sealed class FfftpImportTests
{
    // マスターパスワードを決めていないとき（DefaultPassword）に「hakobune-pass」を保存したもの（初期化ベクトルは 00〜0f にした）
    private const string DefaultMasterPassword = "0C000102030405060708090a0b0c0d0e0f:6adeef63e786b046f786f7be33434920ad7a15c22e60a6b73cad709f133b5992";

    // マスターパスワード「hakobune-master」で「hakobune-pass」を保存したもの
    private const string CustomMasterPassword = "0C000102030405060708090a0b0c0d0e0f:57002f455d023266a80c3b506acdbbb3cea1e601639be0638d4d44f20372f5c3";

    // CredentialSalt = 0x12345678 のときの、DefaultPassword の確かめる値
    private const string DefaultMasterCheck = "G@BLG@NIHOJOGFIOMBMKA@EMKHEGKOH@IGNNFDOM";

    private const string Ini = """
        # Do not edit this file.
        [FFFTP]
        Version=5700
        CredentialSalt=305419896
        CredentialCheck=G@BLG@NIHOJOGFIOMBMKA@EMKHEGKOH@IGNNFDOM
        [FFFTP\Options]
        SetNum=6
        [FFFTP\Options\DefaultHost]
        Pasv=0
        [FFFTP\Options\Host0]
        Set=32768
        HostName=\E4\BB\95\E4\BA\8B
        [FFFTP\Options\Host1]
        Set=1
        HostName=\E3\82\B7\E3\83\A7\E3\83\83\E3\83\97\EF\BC\88\E6\9C\AC\E7\95\AA\EF\BC\89
        HostAdrs=ftp.example.com
        UserName=web
        Password=0C000102030405060708090a0b0c0d0e0f:6adeef63e786b046f786f7be33434920ad7a15c22e60a6b73cad709f133b5992
        LocalDir=C:\\Users\\\E7\AE\B1\E8\88\9F\\shop
        RemoteDir=/var/www/html
        FTPIS=0
        NoEncryption=0
        NameKanji=0
        ThreadCount=4
        [FFFTP\Options\Host2]
